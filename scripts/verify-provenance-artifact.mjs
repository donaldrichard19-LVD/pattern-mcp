#!/usr/bin/env node
/**
 * verify-provenance-artifact.mjs
 *
 * Feature 2 (Decision Provenance) P1's test plan, per
 * pattern-ledger-integrity-and-provenance-spec.md: "Snapshot-test the
 * markdown output against fixture entries for formatting stability."
 *
 * Imports formatProvenanceArtifact directly (no MCP server needed -- it's
 * a pure function of a LedgerEntry) and asserts its output against
 * hand-written expected markdown for a fixed set of fixture entries
 * covering the real shapes a ledger entry can take: a scored use_existing
 * verdict, a custom_build verdict (no candidates), a cache-hit entry, one
 * with a null snapshot_ref (no git repo at judgment time), and one with
 * an empty checklist. A byte-for-byte mismatch here means the format
 * changed, not that time passed -- the function reads nothing but its
 * input argument.
 *
 * Run: node scripts/verify-provenance-artifact.mjs (after `npm run build`)
 * Exits non-zero on any failed assertion.
 */
process.env.PATTERN_NO_AUTOSTART = "1";

const { formatProvenanceArtifact } = await import("../dist/index.js");

let failures = 0;
function check(label, actual, expected) {
  if (actual === expected) {
    console.log(`  ok: ${label}`);
  } else {
    console.error(`  FAIL: ${label}`);
    console.error("--- expected ---");
    console.error(expected);
    console.error("--- actual ---");
    console.error(actual);
    failures++;
  }
}

const BASE = {
  id: "fixture-0001",
  timestamp: "2026-09-02T12:00:00.000Z",
  project_id: "fixture-project",
  feature_id: "fixture-feature",
  component_need: "success or failure toast notification",
  domain: "Airbnb-style rental marketplace",
  framework: "React + Tailwind",
  checklist: ["auto-dismisses after a few seconds", "supports success and error variants"],
  checklist_source: "extracted",
  candidates_evaluated: [{ source: "shadcn", name: "Sonner toast", url: "https://example.com/sonner", coverage_pct: 100 }],
  verdict: "use_existing",
  chosen_candidate: "Sonner toast",
  confidence: "high",
  reason: "scored",
  coverage: "8/8 (100%)",
  cost_usd: 0.14,
  cache_hit: false,
  project_conventions_snapshot: null,
  file_path: null,
  snapshot_ref: "a1b2c3d4e5f60718293a4b5c6d7e8f9012345678",
  last_verified_live: null,
  live_status: "unknown",
};

console.log("1. A fresh, scored use_existing verdict with one candidate");
check(
  "matches expected markdown exactly",
  formatProvenanceArtifact(BASE),
  [
    "## Pattern decision: success or failure toast notification",
    "",
    "- **Verdict:** use_existing (confidence: high)",
    "- **Reason:** scored",
    "- **Coverage:** 8/8 (100%)",
    "- **Domain:** Airbnb-style rental marketplace",
    "- **Framework:** React + Tailwind",
    "- **Snapshot:** `a1b2c3d4e5f60718293a4b5c6d7e8f9012345678`",
    "- **Judged at:** 2026-09-02T12:00:00.000Z",
    "",
    "### Requirements checked",
    "- auto-dismisses after a few seconds",
    "- supports success and error variants",
    "",
    "### Candidates compared",
    "| Source | Name | Coverage | Chosen |",
    "| --- | --- | --- | --- |",
    "| shadcn | Sonner toast | 100 | ✓ |",
    "",
    "_Generated by Pattern (`export_ledger_provenance`) from ledger entry `fixture-0001`._",
  ].join("\n")
);

console.log("\n2. A custom_build verdict -- no candidates, no chosen_candidate");
const customBuild = {
  ...BASE,
  id: "fixture-0002",
  verdict: "custom_build",
  chosen_candidate: null,
  candidates_evaluated: [],
  coverage: null,
  confidence: "low",
};
check(
  "candidates section explains the custom_build gap instead of an empty table",
  formatProvenanceArtifact(customBuild),
  [
    "## Pattern decision: success or failure toast notification",
    "",
    "- **Verdict:** custom_build (confidence: low)",
    "- **Reason:** scored",
    "- **Coverage:** n/a",
    "- **Domain:** Airbnb-style rental marketplace",
    "- **Framework:** React + Tailwind",
    "- **Snapshot:** `a1b2c3d4e5f60718293a4b5c6d7e8f9012345678`",
    "- **Judged at:** 2026-09-02T12:00:00.000Z",
    "",
    "### Requirements checked",
    "- auto-dismisses after a few seconds",
    "- supports success and error variants",
    "",
    "### Candidates compared",
    "_No existing candidate met the bar -- Pattern recommended a custom build. Pattern doesn't persist the custom-build reference (Mobbin/Figma) to the ledger, so it isn't reproducible here._",
    "",
    "_Generated by Pattern (`export_ledger_provenance`) from ledger entry `fixture-0002`._",
  ].join("\n")
);

console.log("\n3. A ledger cache-hit entry -- empty checklist, marked served-from-cache");
const cacheHit = { ...BASE, id: "fixture-0003", reason: "ledger_cache_hit", cache_hit: true, checklist: [], cost_usd: 0 };
check(
  "checklist section explains the empty checklist, cache-hit noted on the Judged at line",
  formatProvenanceArtifact(cacheHit),
  [
    "## Pattern decision: success or failure toast notification",
    "",
    "- **Verdict:** use_existing (confidence: high)",
    "- **Reason:** ledger_cache_hit",
    "- **Coverage:** 8/8 (100%)",
    "- **Domain:** Airbnb-style rental marketplace",
    "- **Framework:** React + Tailwind",
    "- **Snapshot:** `a1b2c3d4e5f60718293a4b5c6d7e8f9012345678`",
    "- **Judged at:** 2026-09-02T12:00:00.000Z (served from ledger cache hit)",
    "",
    "### Requirements checked",
    "_No checklist recorded for this entry._",
    "",
    "### Candidates compared",
    "| Source | Name | Coverage | Chosen |",
    "| --- | --- | --- | --- |",
    "| shadcn | Sonner toast | 100 | ✓ |",
    "",
    "_Generated by Pattern (`export_ledger_provenance`) from ledger entry `fixture-0003`._",
  ].join("\n")
);

console.log("\n4. snapshot_ref null -- project root wasn't a git repo at judgment time");
const noGit = { ...BASE, id: "fixture-0004", snapshot_ref: null };
check(
  "Snapshot line explains the null case in prose instead of printing null",
  formatProvenanceArtifact(noGit),
  [
    "## Pattern decision: success or failure toast notification",
    "",
    "- **Verdict:** use_existing (confidence: high)",
    "- **Reason:** scored",
    "- **Coverage:** 8/8 (100%)",
    "- **Domain:** Airbnb-style rental marketplace",
    "- **Framework:** React + Tailwind",
    "- **Snapshot:** not available (project root wasn't a git repository at judgment time)",
    "- **Judged at:** 2026-09-02T12:00:00.000Z",
    "",
    "### Requirements checked",
    "- auto-dismisses after a few seconds",
    "- supports success and error variants",
    "",
    "### Candidates compared",
    "| Source | Name | Coverage | Chosen |",
    "| --- | --- | --- | --- |",
    "| shadcn | Sonner toast | 100 | ✓ |",
    "",
    "_Generated by Pattern (`export_ledger_provenance`) from ledger entry `fixture-0004`._",
  ].join("\n")
);

console.log("\n5. Solo Dev design-system architecture P3: a design_system-sourced candidate renders distinctly from an external library");
const designSystemSourced = {
  ...BASE,
  id: "fixture-0005",
  candidates_evaluated: [{ source: "design_system", name: "PricingCard", url: null, coverage_pct: 87.5 }],
  chosen_candidate: "PricingCard",
  coverage: "7/8 (87.5%)",
  confidence: "low",
};
check(
  "Candidates table renders design_system as the source, plus a distinguishing note absent for external-library entries",
  formatProvenanceArtifact(designSystemSourced),
  [
    "## Pattern decision: success or failure toast notification",
    "",
    "- **Verdict:** use_existing (confidence: low)",
    "- **Reason:** scored",
    "- **Coverage:** 7/8 (87.5%)",
    "- **Domain:** Airbnb-style rental marketplace",
    "- **Framework:** React + Tailwind",
    "- **Snapshot:** `a1b2c3d4e5f60718293a4b5c6d7e8f9012345678`",
    "- **Judged at:** 2026-09-02T12:00:00.000Z",
    "",
    "### Requirements checked",
    "- auto-dismisses after a few seconds",
    "- supports success and error variants",
    "",
    "### Candidates compared",
    "| Source | Name | Coverage | Chosen |",
    "| --- | --- | --- | --- |",
    "| design_system | PricingCard | 87.5 | ✓ |",
    "",
    "_Sourced from this project's own registered design system (`register_design_system`), not an external library._",
    "",
    "_Generated by Pattern (`export_ledger_provenance`) from ledger entry `fixture-0005`._",
  ].join("\n")
);

console.log("\n6. Determinism: the same entry object formatted twice produces byte-identical output");
check("two calls on the same fixture match exactly", formatProvenanceArtifact(BASE), formatProvenanceArtifact(BASE));

console.log(failures === 0 ? "\nAll checks passed." : `\n${failures} check(s) FAILED.`);
process.exit(failures === 0 ? 0 : 1);
